-- AI GROUP CHAT · Supabase 스키마 (닉네임+입장코드만으로 참여하는 단톡방)
-- 실행: psql 또는 Supabase SQL Editor

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  room_code text not null default 'leebutcher',
  sender text not null,
  badge text default '',
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists chat_messages_room_created_idx
  on public.chat_messages (room_code, created_at);

alter table public.chat_messages enable row level security;

drop policy if exists "Allow anon select" on public.chat_messages;
drop policy if exists "Allow anon insert" on public.chat_messages;

create policy "Allow anon select" on public.chat_messages
  for select to anon, authenticated using (true);

create policy "Allow anon insert" on public.chat_messages
  for insert to anon, authenticated with check (
    char_length(content) > 0 and char_length(content) <= 2000
    and char_length(sender) > 0 and char_length(sender) <= 30
    and char_length(room_code) between 1 and 40
  );

grant select, insert on public.chat_messages to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
